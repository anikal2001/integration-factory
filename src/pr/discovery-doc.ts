// Builds the discovery doc a browser-onboarding PR carries: sanitized endpoint tables,
// capability candidates, enumeration candidates, the capture scaffold, and an honest
// failure log. NEVER the HAR — it holds live cookies/tokens. Wording comes from the plan
// and profile, so the same builder documents a marketplace, a payments dashboard, or a
// SaaS admin console.

import type { CapturedRoute } from '../capture/playwright-capture.js';
import type { CapabilityRouteCandidate } from '../capture/capability-extract.js';
import type { EnumerationCandidate } from '../capture/enumeration-extract.js';
import type { DiscoveryReport } from '../discovery/surface-navigator.js';
import type { DiscoveryPlan } from '../discovery/plan.js';

export interface DiscoveryDocInput {
  targetName: string;
  codebaseName: string;
  plan: DiscoveryPlan;
  startUrl: string;
  endpoints: CapturedRoute[];
  capabilityCandidates: CapabilityRouteCandidate[];
  enumerationCandidates: EnumerationCandidate[];
  discovery: DiscoveryReport;
  captureScaffold?: { relPath: string; content: string };
  registration: string[];
  scaffoldPath: string;
  failures: string[];
  generatedAtIso: string;
}

function table(rows: string[][], header: string[]): string {
  const line = (r: string[]) => `| ${r.join(' | ')} |`;
  return [line(header), line(header.map(() => '---')), ...rows.map(line)].join('\n');
}

const cell = (value: string): string => value.replace(/\|/g, '\\|');

export function buildDiscoveryDoc(input: DiscoveryDocInput): string {
  const endpointRows = input.endpoints
    .slice(0, 60)
    .map((e) => [e.method, String(e.status), (e.observedDuring ?? []).join(', '), cell(e.url)]);
  const capabilityRows = input.capabilityCandidates
    .slice(0, 60)
    .map((c) => [c.capability, String(c.score), c.method, cell(c.url), c.reason]);
  const enumerationRows = input.enumerationCandidates
    .slice(0, 20)
    .map((c) => [c.control, String(c.score), c.method, cell(c.url), c.reason]);
  const enumerating = input.plan.surfaces.flatMap((s) => (s.controls ?? []).filter((c) => c.enumerate).map((c) => c.id));

  return `# ${input.targetName} — integration discovery (browser-captured scaffold)

Generated by \`integration-factory onboard\` on ${input.generatedAtIso} from an
authenticated browser session, using the \`${input.plan.id}\` discovery plan.
**This is a scaffold + investigation artifact, not a working integration.** The raw HAR is
intentionally NOT committed (it contains live session cookies/tokens); only the sanitized
endpoint list below is included.

## Auth model (confirm from the session)
The capture ran against a logged-in session saved as a Playwright \`storageState\`
(cookies + localStorage). Map the auth-bearing cookies/tokens onto this codebase's
credential model: usually a cookie session, or a bearer/CSRF token if one is minted.
Do NOT commit the storageState or any cookie values.

## Captured API endpoints
Distinct XHR/fetch endpoints observed while exercising \`${input.startUrl}\`:

${endpointRows.length ? table(endpointRows, ['method', 'status', 'observed during', 'url (templatized)']) : '_none captured — the flow may not have exercised the APIs, or was blocked._'}

## Capability route candidates
The navigator correlated network activity with the plan surface or control being
exercised (${input.plan.surfaces.map((s) => s.id).join(', ')}). These are candidates to
verify from request/response shapes, not proof that a route implements the capability:

${capabilityRows.length ? table(capabilityRows, ['capability', 'score', 'method', 'url', 'why']) : '_none classified._'}

Discovery reached: ${input.discovery.phasesReached.join(', ')}. It used
${input.discovery.interactions} throttled interactions and ${input.discovery.navigations}
navigations.${input.discovery.stopReason ? ` It stopped at \`${input.discovery.stopReason}\`.` : ''}

The navigator never submits, saves, publishes, purchases, pays, deletes, or changes
account state. Mutating routes require a separate explicitly authorized test account and
human confirmation; they cannot be inferred safely from this read-only run.

## Enumerated reference data
${enumerating.length ? `Endpoints heuristically flagged while enumerating ${enumerating.join(', ')} (confirm which returns the full tree/list):` : '_The plan has no enumerating controls._'}

${enumerationRows.length ? table(enumerationRows, ['control', 'score', 'method', 'url', 'why']) : enumerating.length ? '_none flagged — inspect the endpoints above manually._' : ''}

${input.captureScaffold ? `## Capture scaffold
Written to \`${input.captureScaffold.relPath}\` on this branch. Fill in the response
shapes from the candidates above.

\`\`\`ts
${input.captureScaffold.content}
\`\`\`
` : ''}
## Integration registration (follow-up)
Scaffold \`${input.scaffoldPath}\` in ${input.codebaseName} and register it:
${input.registration.length ? input.registration.map((s) => `- ${s}`).join('\n') : '- (no registration steps listed in the profile)'}

Fill each contract method from the captured routes above.

## Failure log — where the automated flow stopped
${input.failures.length ? input.failures.map((f) => `- ${f}`).join('\n') : '- (none recorded this run)'}
`;
}
